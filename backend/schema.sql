-- First backend step: representative registrations.
-- Run this in the CloudBase PostgreSQL SQL editor after checking the environment.

create table if not exists public.delegates (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(trim(name)) between 1 and 80),
  delegate_no text not null unique check (char_length(trim(delegate_no)) between 1 and 40),
  venue_preference smallint not null check (venue_preference between 1 and 5),
  created_at timestamptz not null default now()
);

alter table public.delegates enable row level security;

-- Start with no client access, then allow public visitors to submit only the
-- registration fields. They cannot read, edit, or delete registrations.
revoke all on table public.delegates from public, anon, authenticated;
revoke all on sequence public.delegates_id_seq from public, anon, authenticated;
grant insert (name, delegate_no, venue_preference) on table public.delegates to anon;
grant usage on sequence public.delegates_id_seq to anon;

drop policy if exists "Public can submit registrations" on public.delegates;
create policy "Public can submit registrations"
  on public.delegates
  for insert
  to anon
  with check (true);
