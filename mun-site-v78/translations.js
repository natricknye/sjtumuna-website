window.munTranslate = function (key, values = {}) {
  const selectedTranslations = window.MUN_TRANSLATIONS[currentLanguage] || {};
  let message = selectedTranslations[key] ?? window.MUN_TRANSLATIONS.en[key] ?? window.MUN_TRANSLATIONS.zh[key] ?? key;
  for (const [name, value] of Object.entries(values)) {
    const replacement = selectedTranslations[value]
      ? window.munTranslate(value)
      : String(value);
    message = message.replaceAll(`{{${name}}}`, replacement);
  }
  return message;
};

window.munShowNotice = function (element, key, values = {}) {
  element.dataset.messageKey = key;
  element.messageValues = values;
  element.textContent = window.munTranslate(key, values);
  element.classList.add("show");
};

