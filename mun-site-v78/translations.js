document.querySelectorAll(".language-more-toggle").forEach((toggle) => {
  const wrapper = toggle.closest(".language-more");
  const menuItems = [...wrapper.querySelectorAll('[role="menuitem"]')];
  const setOpen = (open) => {
    if (!open) wrapper.classList.remove("pinned");
    wrapper.classList.toggle("open", open);
    toggle.setAttribute("aria-expanded", String(open));
  };
  toggle.addEventListener("click", () => {
    if (wrapper.classList.contains("open") && wrapper.classList.contains("pinned")) {
      setOpen(false);
    } else {
      wrapper.classList.add("pinned");
      setOpen(true);
    }
  });
  wrapper.addEventListener("pointerenter", (event) => {
    if (event.pointerType !== "touch") setOpen(true);
  });
  wrapper.addEventListener("pointerleave", () => {
    if (!wrapper.classList.contains("pinned") && !menuItems.includes(document.activeElement)) setOpen(false);
  });
  wrapper.addEventListener("focusin", (event) => {
    if (menuItems.includes(event.target)) setOpen(true);
  });
  wrapper.addEventListener("focusout", (event) => {
    if (!wrapper.contains(event.relatedTarget)) {
      setOpen(false);
    }
  });
  wrapper.addEventListener("keydown", (event) => {
    const activeIndex = menuItems.indexOf(document.activeElement);
    if (event.key === "Escape") {
      toggle.focus();
      setOpen(false);
      event.preventDefault();
      return;
    }
    if (event.key === "ArrowDown" || event.key === "ArrowUp" || event.key === "Home" || event.key === "End") {
      event.preventDefault();
      setOpen(true);
      const nextIndex = event.key === "Home"
        ? 0
        : event.key === "End"
          ? menuItems.length - 1
          : activeIndex < 0
            ? (event.key === "ArrowDown" ? 0 : menuItems.length - 1)
            : (activeIndex + (event.key === "ArrowDown" ? 1 : -1) + menuItems.length) % menuItems.length;
      menuItems[nextIndex]?.focus();
    }
  });
});
