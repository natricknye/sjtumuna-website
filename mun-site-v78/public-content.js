window.renderPublicContent = function (language) {
  const copy = conferenceCopy[language === "zh" ? "zh" : "en"];
  const about = document.querySelector("#about-content");
  const committees = document.querySelector("#committees-content");
  const notice = document.querySelector("#notice-content");
  if (about) about.innerHTML = renderAbout(copy);
  if (committees) committees.innerHTML = renderCommittees(copy);
  if (notice) notice.innerHTML = renderNotice(copy);
};

window.renderPublicContent(document.documentElement.lang === "en" ? "en" : "zh");
