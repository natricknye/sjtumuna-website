function agendaEventsFor(committee) {
  return [
    ...venueSessions.map((session) => ({ ...session, room: committee.rooms[session.date], shared: false })),
    ...venueSharedEvents,
  ].sort((a, b) => `${a.date} ${a.time.slice(0, 5)}`.localeCompare(`${b.date} ${b.time.slice(0, 5)}`));
}

function agendaRoomSummary(committee, zh) {
  const lang = zh ? "zh" : "en";
  const grouped = new Map();
  Object.entries(committee.rooms).forEach(([date, room]) => {
    if (!grouped.has(room)) grouped.set(room, []);
    grouped.get(room).push(venueDays[date][lang]);
  });
  return [...grouped.entries()].map(([room, dates]) => `${dates.join(" / ")} ${venueRoomNames[room][lang]}`).join(" · ");
}

